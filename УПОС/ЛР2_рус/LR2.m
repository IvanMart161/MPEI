clear; clc; close all;

%% ========================================================================
% ЧАСТЬ 1: ТЕОРЕТИЧЕСКАЯ
% Расчет ожидаемых коэффициентов отражения ненагруженных аттенюаторов
% =========================================================================
disp('--- 1. Теоретические параметры ---');
Z0 = 50; % Волновое сопротивление
attenuators_dB = [3, 6, 10]; 

% Если порт OUT ответвителя разомкнут (Open Circuit), вся мощность отражается
% Коэффициент отражения нагрузки (ХХ) в дБ равен 0.
% При прохождении через аттенюатор сигнал ослабляется дважды (туда и обратно).
Gamma_theoretical_dB = -2 * attenuators_dB; 

for i = 1:length(attenuators_dB)
    fprintf('Ненагруженный аттенюатор %d дБ: ожидаемый коэфф. отражения = %d дБ\n', ...
        attenuators_dB(i), Gamma_theoretical_dB(i));
end
disp(' ');

%% ========================================================================
% ЧАСТЬ 2: ЭКСПЕРИМЕНТАЛЬНАЯ - АЧХ ФИЛЬТРА (По Таблице 1)
% =========================================================================
% Данные из Таблицы 1 "Измерение Kf" 
f_filter = [100, 200, 300, 400, 500, 600, 700, 800, 900, 1000, 1025, 1050, ...
            1100, 1125, 1150, 1200, 1250, 1350]; % Частоты, МГц
        
P_uncal = [-2.82, -2.90, -2.86, -3.10, -3.39, -3.85, -4.16, -4.49, -5.00, ...
           -5.85, -6.18, -6.40, -8.54, -10.26, -13.76, -20.12, -30.00, -36.70]; % Измерения с фильтром, дБм[cite: 9]
       
P_cal = [-5.27, -3.03, -2.93, -3.08, -3.32, -3.67, -3.73, -4.04, -4.25, ...
         -4.30, -4.39, -4.50, -4.42, -4.21, -4.35, -4.24, -4.06, -4.37]; % Калибровка (без фильтра), дБм[cite: 9]

% Расчет коэффициента передачи (АЧХ)
K_f = P_uncal - P_cal; %[cite: 9]

% Поиск частоты среза по уровню -3 дБ (интерполяция)
f_cutoff_3dB = interp1(K_f, f_filter, -3, 'linear');

% Построение графика АЧХ
figure('Name', 'АЧХ Фильтра', 'NumberTitle', 'off');
plot(f_filter, K_f, 'b-', 'LineWidth', 2); hold on;
yline(-3, 'r--', 'Уровень -3 дБ', 'LabelHorizontalAlignment', 'left');
plot(f_cutoff_3dB, -3, 'ro', 'MarkerSize', 8, 'MarkerFaceColor', 'r');
grid on;
title('Амплитудно-частотная характеристика (АЧХ) фильтра');
xlabel('Частота f, МГц');
ylabel('Коэффициент передачи K_f(f), дБ');
text(f_cutoff_3dB + 20, -2, sprintf('f_{среза} = %.1f МГц', f_cutoff_3dB), 'Color', 'red');

fprintf('--- 2. Результаты АЧХ ---\n');
fprintf('Измеренная частота среза (по уровню -3 дБ): %.2f МГц\n\n', f_cutoff_3dB);

%% ========================================================================
% ЧАСТЬ 3: ЭКСПЕРИМЕНТАЛЬНАЯ - КОЭФФИЦИЕНТ ОТРАЖЕНИЯ И КСВН
% =========================================================================
% ВНИМАНИЕ: Ниже приведены аппроксимированные данные, снятые с графиков 9 и 10 отчета.
% ЗАМЕНИТЕ ИХ НА ВАШИ РЕАЛЬНЫЕ ЭКСПЕРИМЕНТАЛЬНЫЕ ЗНАЧЕНИЯ!

f_refl = 500:100:1300; % Сетка частот, МГц

% Уровни мощности на порте CPL OUT (дБм) для разных нагрузок
P_open = [-23.5, -24.2, -24.0, -21.5, -22.5, -21.5, -21.0, -19.5, -20.5]; % Разомкнутая цепь
P_load = [-40.0, -42.0, -40.0, -39.0, -40.0, -41.0, -41.0, -41.0, -40.0]; % Согласованная нагрузка 50 Ом
P_filt = [-39.0, -39.0, -36.5, -34.5, -35.5, -36.0, -28.0, -22.0, -21.0]; % Фильтр + нагрузка 50 Ом

% Расчет коэффициента отражения (Return Loss) для фильтра
% Вычисляется как разница между отражением от фильтра и калибровочным 
% отражением от разомкнутой цепи (где Г = 0 дБ)
Return_Loss_dB = P_filt - P_open; 

% Перевод Return Loss из дБ в линейный модуль коэффициента отражения |Г|
Gamma_lin = 10.^(Return_Loss_dB / 20);

% Расчет Коэффициента Стоячей Волны Напряжения (КСВН)
KSVN = (1 + Gamma_lin) ./ (1 - Gamma_lin);

% Построение графиков мощностей
figure('Name', 'Мощности отражения', 'NumberTitle', 'off');
plot(f_refl, P_open, 'b-', 'LineWidth', 1.5); hold on;
plot(f_refl, P_load, 'r--', 'LineWidth', 1.5);
plot(f_refl, P_filt, 'y-.', 'LineWidth', 2);
grid on;
title('Сравнительная зависимость мощности (CPL OUT)');
xlabel('Частота f, МГц');
ylabel('Мощность P, дБм');
legend('Разомкнутая цепь', 'С нагрузкой 50 Ом', 'Фильтр + нагрузка', 'Location', 'best'); %[cite: 14]

% Построение графика КСВН
figure('Name', 'Зависимость КСВН', 'NumberTitle', 'off');
plot(f_refl, KSVN, 'b-', 'LineWidth', 2);
grid on;
title('Частотная зависимость КСВН фильтра'); %[cite: 14]
xlabel('Частота f, МГц');
ylabel('КСВН');
ylim([0, max(KSVN)+5]);

%% ========================================================================
% ЧАСТЬ 4: КОЭФФИЦИЕНТЫ ОТРАЖЕНИЯ АТТЕНЮАТОРОВ
% =========================================================================
% Данные приближены по графику 12. ЗАМЕНИТЕ НА СВОИ!
P_att_3dB  = [-29, -29, -20, -27, -26, -25, -26, -25, -24]; %[cite: 15]
P_att_6dB  = [-35, -35, -33, -32, -41, -31, -30, -29, -30]; %[cite: 15]
P_att_10dB = [-42, -45, -45, -40, -42, -44, -44, -34, -42]; %[cite: 15]

% Расчет коэффициентов отражения
RL_att_3 = P_att_3dB - P_open;
RL_att_6 = P_att_6dB - P_open;
RL_att_10 = P_att_10dB - P_open;

figure('Name', 'Отражение аттенюаторов', 'NumberTitle', 'off');
plot(f_refl, RL_att_3, 'b-.', 'LineWidth', 1.5); hold on;
plot(f_refl, RL_att_6, 'r--', 'LineWidth', 1.5);
plot(f_refl, RL_att_10, 'y-', 'LineWidth', 1.5);
grid on;
title('Коэффициент отражения для ненагруженных аттенюаторов'); %[cite: 15]
xlabel('Частота f, МГц');
ylabel('Коэффициент отражения, дБ');
legend('3 дБ', '6 дБ', '10 дБ', 'Location', 'best');