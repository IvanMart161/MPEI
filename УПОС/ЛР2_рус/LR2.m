    -1.52, -1.33, -1.29, -1.36, -1.22, -1.27, -1.37, -1.35, -1.26, -1.36, ...
    -1.37, -1.4, -1.48, -1.6, -1.72, -1.77, -2.02, -2.12, -2.12, -2.12]; % 

P_cal2 = [-2.18, -1.5, -1.68, -1.65, -1.48, -1.65, -1.81, -1.89, -1.75, ... % 
