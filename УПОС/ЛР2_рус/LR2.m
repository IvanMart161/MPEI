    -2.26, -2.33, -2.21, -2.23, -2.2, -1.93, -2.43, -3.64, -4.23, -4]; % Калибровка (без фильтра), дБм

% Расчет коэффициента передачи (АЧХ)
K_f = P_uncal - P_cal;


% Построение графика АЧХ
