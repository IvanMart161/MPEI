%% ========================================================================
% ЧАСТЬ 1: ТЕОРЕТИЧЕСКАЯ
% Расчет ожидаемых коэффициентов отражения ненагруженных аттенюаторов
% =========================================================================
disp('--- 1. Теоретические параметры ---');
Z0 = 50; % Волновое сопротивление
attenuators_dB = [3, 6, 10]; 

% Если порт OUT ответвителя разомкнут (Open Circuit), вся мощность отражается
% Коэффициент отражения нагрузки (ХХ) в дБ равен 0.
% При прохождении через аттенюатор сигнал ослабляется дважды (туда и обратно).
Gamma_theoretical_dB = -2 * attenuators_dB; 

for i = 1:length(attenuators_dB)
    fprintf('Ненагруженный аттенюатор %d дБ: ожидаемый коэфф. отражения = %d дБ\n', ...
        attenuators_dB(i), Gamma_theoretical_dB(i));
end
disp(' ');

%% ========================================================================
