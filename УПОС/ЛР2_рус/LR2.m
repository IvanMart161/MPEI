    -1.82, -1.83, -1.91, -1.91, -2.03, -2.22, -2.29, -2.45, -2.6, -2.6]; % 

P_open = [-21, -19.3, -19.92, -20.71, -21, -20.6, -20.4, -21.53, -21.8, ...
    -21.36, -21.24, -20.62, -21.6, -20.03, -20.45, -20.88, -21.38, -20.78, -20.65, ...
    -20.89, -20.61, -20.79, -21.3, -21.07, -21.30, -20.93, -21.1, -21.18, -20.49, -20.49, ...
