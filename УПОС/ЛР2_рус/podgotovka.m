1% Скрипт для расчета номиналов П-образного, Т-образного аттенюаторов
% и резистивного делителя мощности 1:2
Z0 = 50; % Волновое сопротивление тракта, Ом
attenuations_dB = [3, 6, 10]; % Заданные коэффициенты ослабления

fprintf('Расчет элементов (Z0 = %d Ом)\n\n', Z0);

% --- 1. П-образный аттенюатор ---
fprintf('1. П-образный аттенюатор\n');
fprintf('------------------------------------------------------\n');
fprintf(' Затухание (дБ) | R1, R2 (паралл.), Ом | R3 (послед.), Ом\n');
fprintf('------------------------------------------------------\n');
for A = attenuations_dB
    K = 10^(A / 20); % Коэффициент по напряжению
    R_par_pi = Z0 * (K + 1) / (K - 1);
    R_ser_pi = Z0 * (K^2 - 1) / (2 * K);
    fprintf(' %14d | %20.2f | %16.2f\n', A, R_par_pi, R_ser_pi);
end
fprintf('------------------------------------------------------\n\n');

% --- 2. Т-образный аттенюатор ---
fprintf('2. Т-образный аттенюатор\n');
fprintf('------------------------------------------------------\n');
fprintf(' Затухание (дБ) | R1, R2 (послед.), Ом | R3 (паралл.), Ом\n');
fprintf('------------------------------------------------------\n');
for A = attenuations_dB
    K = 10^(A / 20); % Коэффициент по напряжению
    R_ser_t = Z0 * (K - 1) / (K + 1);
    R_par_t = Z0 * (2 * K) / (K^2 - 1);
    fprintf(' %14d | %20.2f | %16.2f\n', A, R_ser_t, R_par_t);
end
fprintf('------------------------------------------------------\n\n');

% --- 3. Резистивный делитель мощности 1:2 ---
fprintf('3. Резистивный делитель мощности 1:2 (схема "Звезда")\n');
fprintf('------------------------------------------------------\n');
R_split = Z0 / 3;
fprintf(' Для согласования всех трех портов на %d Ом:\n', Z0);
fprintf(' R1 = R2 = R3 = %.2f Ом\n', R_split);
fprintf(' Теоретические вносимые потери между портами: 6 дБ.\n');
fprintf('------------------------------------------------------\n');