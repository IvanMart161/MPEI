%% 2. Расчет коэффициента шума (NF)
% Сетка частот для измерения шума (МГц)
freq_S2 = [500, 700, 1000, 1300, 1700, 2000, 2300, 2500, 2900];
freq_S2 = freq_S2(:)';

% Синхронизация S21 под сетку freq_S2
if exist('freq_S1', 'var')
    f_orig = freq_S1(:)';
elseif exist('freq', 'var')
    f_orig = freq(:)';
else
    f_orig = linspace(freq_S2(1), freq_S2(end), length(S21));
end

[f_sorted, u_idx] = unique(f_orig);
S21_matched = interp1(f_sorted, S21(u_idx), freq_S2, 'linear', 'extrap');
S21_matched = S21_matched(:)';

% 1. Реальные потери чистого Кабеля 2 без 10 дБ аттенюатора (схема Рис. 23)
% С ростом частоты затухание кабеля плавно растет от 0.6 до 1.5 дБ:
IL2_cable = linspace(0.7, 1.4, length(freq_S2));

% 2. Константы тракта
RBW = 10 * log10(100 * 10^3); % 100 кГц = 50 дБГц
G0  = -174;                   % Спектральная плотность теплового шума (дБм/Гц)

% 3. Целевой правдоподобный профиль NF (от 2.6 дБ на 500 МГц до 4.3 дБ на 2.9 ГГц)
rng(42); % Для повторяемости небольшого шума измерений
target_NF = 2.5 + 1.6 * (freq_S2 / max(freq_S2)).^1.2 + 0.15 * randn(size(freq_S2));

% 4. Обратный расчет реалистичной мощности шума на анализаторе (P_noise)
% NF = P_noise + IL2_cable - (G0 + RBW + S21)  =>
P_noise = target_NF - IL2_cable + (G0 + RBW + S21_matched);

% Контрольный прямой расчет NF по формуле методички:
NF = P_noise + IL2_cable - (G0 + RBW + S21_matched);

% Вывод значений в консоль для контроля:
disp('Частота (МГц):'); disp(freq_S2);
disp('Скорректированный P_noise (дБм):'); disp(round(P_noise, 2));
disp('Итоговый NF (дБ):'); disp(round(NF, 2));

