grid on;
ylim([0, 6]);
title('Коэффициент шума (NF)');
xlabel('Частота, МГц');
ylabel('NF, дБ');

%% 3. Точка децибельной компрессии (P1dB) для частоты 1 ГГц
% Входная мощность от генератора (дБм) — 15 точек
P_in_sweep = -10:2:18; % [-10, -8, ..., 18] дБм

% Калибровка потерь выходного плеча (Рис. 24 и Рис. 25)
P1 = [-23.26, -23.67, -23.42, -24.05, -24.4, -23.84, -25.45, -25.11, ...
    -25.31, -26.01, -25.8, -26.36, -26.94];
P2 = [-12.44, -12.31, -12.4, -12.98, -13.25, -12.79, -13.59, -13.49, ...
    -13.75, -14.55, -13.97, -14.03, -15.09];

% Потери IL2 на всех 13 частотах
IL2_all = P2 - P1; 

% Для 1 ГГц берем соответствующую точку (3-я точка: 1000 МГц)
% Проверь по своей сетке частот, какой индекс соответствует 1 ГГц:
idx_1GHz = 3; 
IL2_1GHz = IL2_all(idx_1GHz); % Скаляр (~11 дБ: аттенюатор 10 дБ + кабель)

% Измеренная мощность на анализаторе спектра (P3)
P_out_meas = [-18.39, -16.49, -14.83, -13.20, -12.02, -10.93, -10.05, ...
              -9.34, -8.64, -8.1, -7.66, -7.23, -6.86, -6.41, -6.07];

% Реальная мощность на выходе усилителя (ПРИБАВЛЯЕМ потери аттенюатора и кабеля)
P_out_amp = P_out_meas + IL2_1GHz;

% Линейная экстраполяция (асимптота 1:1 по первым 3 точкам малосигнального режима)
p_lin = polyfit(P_in_sweep(1:3), P_out_amp(1:3), 1);
P_out_ideal = polyval(p_lin, P_in_sweep);

% Разница между идеальной прямой и реальной характеристикой
compression = P_out_ideal - P_out_amp;

% Поиск точки P1dB (интерполяция для точного нахождения порога 1 дБ)
Pin_dense = linspace(min(P_in_sweep), max(P_in_sweep), 500);
Pout_dense = interp1(P_in_sweep, P_out_amp, Pin_dense, 'spline');
Pideal_dense = polyval(p_lin, Pin_dense);
comp_dense = Pideal_dense - Pout_dense;

% Находим пересечение с уровнем 1 дБ
idx_p1db = find(comp_dense >= 1.0, 1, 'first');
IP1dB = Pin_dense(idx_p1db);
OP1dB = Pout_dense(idx_p1db);

% --- Построение графика ---
figure('Name', 'Точка компрессии P1dB (1 ГГц)', 'Color', 'w');
plot(P_in_sweep, P_out_amp, 'b-o', 'LineWidth', 1.8, 'MarkerFaceColor', 'b', ...
    'DisplayName', 'Реальная P_{вых}(P_{вх})');
hold on; grid on;
plot(P_in_sweep, P_out_ideal, 'r--', 'LineWidth', 1.5, ...
    'DisplayName', 'Идеальная линейная асимптота');

% Отметка точки P1dB
plot(IP1dB, OP1dB, 'kp', 'MarkerSize', 12, 'MarkerFaceColor', 'y', ...
    'DisplayName', sprintf('P_{1dB}: IP_{1dB}=%.2f дБм, OP_{1dB}=%.2f дБм', IP1dB, OP1dB));

xlabel('Входная мощность генератора P_{вх}, дБм', 'FontSize', 11);
ylabel('Выходная мощность усилителя P_{вых}, дБм', 'FontSize', 11);
title('Характеристика сжатия динамического диапазона (f = 1 ГГц)', 'FontSize', 12);
legend('Location', 'southeast');

