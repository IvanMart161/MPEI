clear; clc; close all;

%% 1. Измерение коэффициента усиления (S21) и развязки (S12)
% Введите сетку частот (МГц)
freq_S = [500, 600, 700, 800, 900, 1000, 1100, 1200, 1300, 1400, 1500];

% Калибровочные измерения измерительного тракта (уровень без усилителя, дБм)
P2_cal_S = [-10.1, -10.2, -10.5, -10.7, -11.0, -11.2, -11.5, -11.8, -12.0, -12.3, -12.5];

% Измерения уровня сигнала на выходе с подключенным усилителем (дБм)
P1_amp_S = [8.5, 8.6, 8.4, 8.1, 7.5, 6.8, 5.5, 4.0, 2.1, 0.5, -1.5];

% Измерения развязки (усилитель подключен в обратном направлении, дБм)
P_rev_S = [-40, -41, -42, -41, -40, -42, -43, -45, -45, -46, -47];

% Расчет S21 и S12 (дБ) с учетом калибровки
S21 = P1_amp_S - P2_cal_S;
S12 = P_rev_S - P2_cal_S;

%% 2. Расчет коэффициента шума (NF)
% Измеренный уровень шума на анализаторе спектра с усилителем (дБм)
P_noise = [-145, -144, -143, -143, -142, -141, -140, -139, -139, -138, -137];
RBW = 10 * log10(3000); % Полоса RBW в логарифмическом масштабе (например, 3 кГц)
G0 = -174; % Спектральная плотность теплового шума при стандартной температуре (дБм/Гц)

% Потери во втором кабеле (IL2)
IL2 = abs(P2_cal_S); % Оценка потерь на основе калибровки

% Расчет Кш по формуле: Кш = P + IL2 - (G0 + RBW + Kp)
NF = P_noise + IL2 - (G0 + RBW + S21);

%% 3. Построение графиков (АЧХ, Развязка, NF)
figure('Name', 'Результаты ЛР №3 (СВЧ)', 'Position', [100, 100, 1000, 700]);

% График АЧХ (S21)
subplot(2,2,1);
plot(freq_S, S21, '-bo', 'LineWidth', 1.5, 'MarkerFaceColor', 'b');
grid on; title('Коэффициент усиления (S_{21})');
xlabel('Частота, МГц'); ylabel('S_{21}, дБ');

% График Развязки (S12)
subplot(2,2,2);
plot(freq_S, S12, '-ro', 'LineWidth', 1.5, 'MarkerFaceColor', 'r');
grid on; title('Развязка (S_{12})');
xlabel('Частота, МГц'); ylabel('S_{12}, дБ');

% График Коэффициента шума (NF)
subplot(2,2,3);
plot(freq_S, NF, '-go', 'LineWidth', 1.5, 'MarkerFaceColor', 'g');
grid on; title('Коэффициент шума (NF)');
xlabel('Частота, МГц'); ylabel('NF, дБ');

%% 4. Точка децибельной компрессии (P1dB) для центральной частоты (например, 1 ГГц)
% Входная мощность от генератора (дБм)
P_in_sweep = -10:2:20;
% Суммарные потери аттенюатора и кабеля 1 (из калибровки P1 - P2)
IL2_comp = 20.5; 
% Измеренная мощность на анализаторе (P3)
P3_meas = [-2.5, -0.5, 1.5, 3.5, 5.5, 7.5, 9.4, 11.2, 12.5, 13.5, 14.1, 14.5, 14.7, 14.8, 14.9, 15.0];

% Выходная мощность усилителя с учетом потерь тракта
P_out_amp = P3_meas + IL2_comp;

% Идеальная линейная характеристика (определяется по слабому сигналу на линейном участке)
Linear_Gain = P_out_amp(1) - P_in_sweep(1);
P_out_ideal = P_in_sweep + Linear_Gain;

subplot(2,2,4);
plot(P_in_sweep, P_out_ideal, '--k', 'LineWidth', 1.2); hold on;
plot(P_in_sweep, P_out_amp, '-mo', 'LineWidth', 1.5, 'MarkerFaceColor', 'm');
% Линия P1dB (отклонение на 1 дБ от идеальной)
plot(P_in_sweep, P_out_ideal - 1, ':k', 'LineWidth', 1); 

grid on; title('Амплитудная характеристика (P_{1dB})');
xlabel('P_{вх}, дБм'); ylabel('P_{вых}, дБм');
legend('Идеальная АХ', 'Реальная АХ', 'Сдвиг -1 дБ', 'Location', 'SouthEast');