import scipy.io as sio, numpy as np, matplotlib.pyplot as plt, scipy.signal as signal
import psd

mat = sio.loadmat('test1_25p0.mat')
# Кароче тута ствавим эту имбулину, шобы по красоте все было, мы растянем матовский файл многомерный в одномерный массив
x = mat['pdin'].ravel()
y = mat['pdout'].ravel()
Fs = 245.76e6
# Ну чисто пацанская разница между частотой приемника и частотй передатчика. Мы ищем ее для подстройки между входом и выходом, чтобы жетско чилить под маканчика
df = float(mat['rx_freq'][0, 0]) - float(mat['tx_freq'][0, 0])

# Ну тут вообще все просто, вычитаем постоянку mean, чисто для того, чтобы оставить переменку. Этот братик (постоянка) лишний в этой тусовке, он появляется из-за паразитного смещения из-за всяких дисбалансах
y = y - np.mean(y)
# На вайбовых движениях сдвигаем частоту нашего приемника подстраивая его под чатоту передатчика. В реальности из-за всяких непацанских движений их частоты могут быть не синхронизированы по фазе 
y = y * np.exp(2j*np.pi*df/Fs*np.arange(len(y)))

#'full' — все возможные перекрытия (длина len(y) + len(x) − 1);
#'same' — длина как у большего из двух;
#'valid' — только те сдвиги, где окна полностью перекрываются (длина len(y) − len(x) + 1)
#Ищет корреляцию между x и y 
delay = np.argmax(np.abs(np.correlate(y, x, 'valid')))
# Четенкьо обрезаем y массив под x 
y = y[delay:delay + len(x)]
# np.vdot ищет СоПрЯжЕнНоЕ межд x и y. 
# А нафига эта дробь? g = np.vdot(y, x) / np.vdot(y, y) = yᴴx / ‖y‖². Оптимальный комплексный коэффициент 
y = y * (np.vdot(y, x) / np.vdot(y, y))

# Че тут происходит? 
#np.abs(x)**2 — квадраты модулей (мгновенная мощность).
#np.mean(...) — средняя мощность x (RMS²).
#np.sqrt(...) — RMS (root mean square) — «типичная амплитуда».
#Делим оба сигнала на scale.
scale = np.sqrt(np.mean(np.abs(x)**2))
x, y = x/scale, y/scale

d = y - x

# Тут мы задаем коэффициенты фильтра FIR, шоб 2D + 1 = 15 - коэффициенты фильтра 
# D = 7 означает, что окно симметрично: [x[n−7], …, x[n], …, x[n+7]]. Это позволяет фильтру учитывать будущие отсчёты — важно для компенсации непричинных искажений
D = 17

# Ну тут че осталось, то нулями добавили 
# Создаёт массив xp длиной len(x) + 2D, где:
# первые D элементов — нули;
# затем x целиком;
# последние D элементов — нули.
# Чисто чтобы для каждого n (включая края, n = 0 и n = len(x)−1) можно было взять окно длины 2D+1, не выходя за границы массива.
# Без дополнения было бы ваще все печально, для n = 0 пришлось бы брать x[−7:8] — а x[−7] в Python означает «седьмой с конца», а не «ноль». Это дало бы циклический сдвиг вместо нулей, что физически бессмысленно (сигнал «зацикливается»).
xp = np.concatenate([np.zeros(D), x, np.zeros(D)])

#xp[n : n + 2D + 1] - Для индекса n берём окно из 2D+1 = 15 отсчётов, начиная с xp[n]. xp[n : n+15] = [x[n−D], x[n−D+1], …, x[n], …, x[n+D−1], x[n+D]]
#
#[::-1] - По кайфику разворачиваем окно [x[n+D], x[n+D−1], …, x[n], …, x[n−D+1], x[n−D]] (от будущего к прошлому)
# Почему развернуть надо? Свёртка (FIR-фильтр) определяется как:(U @ w)[n] = Σ_{k=0}^{2D} w[k] · x[n + D − k]
# Здесь w[0] умножается на x[n+D], w[1] — на x[n+D−1], …, w[D] — на x[n], …, w[2D] — на x[n−D].
# Чтобы U[n] @ w давал именно это, строка U[n] должна быть:
# U[n] = [x[n+D], x[n+D−1], …, x[n−D]]
# Именно это и даёт [::-1]
#
# np.array([..]) - Собираем все строки в матрицу формы N × 15. Строка n — вектор состояния u_nᵀ.
# Тогда:
#     U @ w — свёртка x с w (вектор длины N);
#     U[n] @ w — скалярное произведение строки на w — значение фильтра в точке n;
#     Uᴴ @ d — корреляция d со строками U (для МНК)
U = np.array([xp[n:n + 2*D + 1][::-1] for n in range(len(x))]) # это матрица «скользящих окон» по сигналу x.

# Метрика NMSE - нормализованная среднеквадратичная ошибка в Дб. NMSE = 10·log10( ‖e‖² / ‖d‖² )
# np.vdot(e, e) = eᴴe = ‖e‖² — энергия остатка.
# np.vdot(d, d) = ‖d‖² — энергия исходной ошибки.
# .real — потому что vdot комплексный, но для eᴴe мнимое = 0; .real подстраховывает от вычислительных хвостов.
# 10·log10 пацанские дБ
nmse = lambda e: 10*np.log10(np.vdot(e, e).real / np.vdot(d, d).real)

# Старый добрый МНК
# Задача: найти w, чтобы U @ w ≈ d
# Минимизируем J(w) = ||d - Uw||^2  (сумма квадратов ошибки)
#
# Решение: w = (U^H U)^(-1) U^H d
#   U^H = conj(U).T — эрмитово сопряжение (транспонирование + комплексное сопряжение).
#   conj нужен, потому что для комплексных чисел скалярное произведение
#   требует сопряжения: <a,b> = a^H b = sum(conj(a[n]) * b[n]).
#   Без conj норма ||a||^2 не была бы вещественной и положительной.
#
# solve(A, b) решает A x = b без явного обращения A:
#   быстрее и численно устойчивее, чем inv(A) @ b. Старый добрый МНК(LS)
#
#   U^H U — корреляция признаков, U^H d — корреляция с целью, деление «убирает» корреляцию между сдвигами x
#
# U @ w = свёртка x с фильтром w — то есть выход FIR-фильтра.
# Мы хотим U @ w ≈ d — фильтр по x должен предсказывать искажения d.
# U[n] @ w — значение фильтра в точке n
UH = U.conj().T
w_ls = np.linalg.solve(UH @ U, UH @ d)

# Регулизированный МНК (Тихонов)
# Обозначения:
#   w — коэффициенты FIR-фильтра (15 штук), которые ищем
#   d — ошибка тракта y - x (вектор длины N)
#   U — матрица окон x (N x 15), строка n = [x[n+7],...,x[n-7]]
#   U @ w — предсказание фильтра
#   e = d - U @ w — остаток
#   J(w) — функция потерь (число, которое минимизируем)
#
# J(w) = ||d - Uw||^2 + sigma^2 * ||w||^2
#   ||d - Uw||^2 — сумма квадратов остатка
#   sigma^2 * ||w||^2 — штраф за большие коэффициенты
#
# Минимум достигается при (U^H U + sigma^2 I) w = U^H d, откуда:
#   w = (U^H U + sigma^2 I)^(-1) U^H d
#
# sigma^2 I поднимает малые собственные числа U^H U -> устойчивое обращение,
# гладкие коэффициенты, меньше переобучения
sigma2 = 1e-2 * len(x)
w_reg = np.linalg.solve(UH @ U + sigma2*np.eye(2*D + 1), UH @ d)

# ================= Leaky LMS (адаптивный алгоритм) =================
# Что это: онлайн-версия Ridge. Вместо того чтобы решать всё сразу
# по формуле (как LS/Ridge), мы идём по сигналу по одному отсчёту
# и постепенно подкручиваем w.
#
# Обозначения:
#   w        — коэффициенты фильтра (15 крутилок), которые ищем
#   d[n]     — цель в момент n (ошибка тракта y - x)
#   U[n]     — окно из 15 отсчётов x вокруг момента n (вектор-строка)
#   U[n] @ w — предсказание фильтра при текущих w
#   e_n      — ошибка предсказания в момент n (одно число)
#   mu       — шаг адаптации (насколько сильно крутить крутилки)
#   lam      — коэффициент утечки (насколько сильно крутилки тянутся к нулю)
#
# Что делаем на каждом шаге:
#   1) e_n = d[n] - U[n] @ w
#        "насколько мы промахнулись" при текущих w.
#
#   2) w = (1 - lam)*w + mu*np.conj(U[n])*e_n
#        "подкрутить крутилки":
#        - (1 - lam)*w       — утечка: чуть-чуть ослабить все w
#                              (чтобы не раздулись до бесконечности)
#        - mu*conj(U[n])*e_n — шаг градиента: сдвинуть w в сторону
#                              уменьшения ошибки (conj нужен для
#                              комплексных сигналов)
#
# Почему 20 эпох:
#   данных мало, за один проход w не успевает сойтись,
#   поэтому проходим по массиву несколько раз.
#
# Связь с Ridge:
#   lam / mu = 1e-2 = sigma^2 / N  — та же регуляризация,
#   что и в Ridge, только в онлайн-форме. При сходимости leaky LMS
#   даёт тот же w, что и Ridge.
#
# Плюсы LMS:
#   - не нужно хранить весь массив U (только текущий отсчёт)
#   - подстраивается на лету (если тракт меняется)
#   - вычислительно дёшев: O(15) на отсчёт вместо O(15^2) для Ridge
# ====================================================================
mu = 0.003
lam = mu * 1e-2
w = np.zeros(2*D + 1, complex)
for epoch in range(20):
    for n in range(len(x)):
        e_n = d[n] - U[n] @ w
        w = (1 - lam)*w + mu*np.conj(U[n])*e_n
w_lms = w

# Оцениваем каждый метод. Для каждого из трёх w (LS, Ridge, LMS) считает:
#     d − U@w — остаток после компенсации;
#     nmse(...) — качество в дБ (чем меньше, тем лучше);
#     np.linalg.norm(w) — норма коэффициентов (чем меньше, тем «проще» фильтр).
for name, w in [('LS', w_ls), ('LS + регуляризация', w_reg), ('LMS с утечкой', w_lms)]:
    print(f'{name:20s} NMSE = {nmse(d - U@w):6.2f} дБ,  ||w|| = {np.linalg.norm(w):.3f}')

w = w_reg
e = d - U @ w

spec = lambda s: psd.psd_welch(s*scale, 2048, signal.windows.blackmanharris(2048), 1024, Fs)
H = lambda w: 20*np.log10(np.abs(np.fft.fftshift(np.fft.fft(w, 2048))))

plt.figure('PSD')
for s in (x, y, d, e):
    P, f = spec(s)
    plt.plot(f/1e6, P)
plt.plot(f/1e6, H(w))
plt.legend(['x', 'y', 'd = y - x', 'остаток e', '|W(f)|'])
plt.xlabel('freq, MHz'); plt.ylabel('PSD, dB/Hz'); plt.grid(True)

plt.figure('Коэффициенты', figsize=(10, 8))

plt.subplot(311)
plt.title('LS (без регуляризации)')
plt.plot(w_ls.real, label='Re')
plt.plot(w_ls.imag, label='Im')
plt.grid(True); plt.legend()

plt.subplot(312)
plt.title('Ridge (с регуляризацией)')
plt.plot(w_reg.real, label='Re')
plt.plot(w_reg.imag, label='Im')
plt.grid(True); plt.legend()

plt.subplot(313)
plt.title('LMS с утечкой')
plt.plot(w_lms.real, label='Re')
plt.plot(w_lms.imag, label='Im')
plt.grid(True); plt.legend()

plt.tight_layout()
plt.show()
